// =============================================================
// Parse LLM output -> normalize { trend_summary, items[] }
// =============================================================
function extractJson(raw) {
  let text = String(raw || '').trim();
  if (!text) return null;

  const fence = text.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) text = fence[1].trim();

  try {
    return JSON.parse(text);
  } catch (e) {
    /* fall through to brace extraction */
  }

  const objectStart = text.indexOf('{');
  const arrayStart = text.indexOf('[');
  let start = -1;
  if (objectStart === -1) start = arrayStart;
  else if (arrayStart === -1) start = objectStart;
  else start = Math.min(objectStart, arrayStart);
  if (start === -1) return null;

  const open = text[start];
  const close = open === '{' ? '}' : ']';
  const end = text.lastIndexOf(close);
  if (end <= start) return null;

  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch (e) {
    return null;
  }
}

function cleanText(v) {
  return String(v || '')
    .replace(/\s+/g, ' ')
    .trim();
}

function validUrl(v) {
  const u = cleanText(v);
  return /^https?:\/\//i.test(u) ? u : '';
}

const inputItem = $input.first();
const raw =
  inputItem.json.output ??
  inputItem.json.text ??
  inputItem.json.response ??
  inputItem.json.content ??
  inputItem.json?.data?.text ??
  '';

const parsed = extractJson(raw);
// Fall back to cleaned RSS data if the LLM response cannot be parsed as JSON
let prior = {};
try {
  prior = $('Clean & Aggregate Articles').first().json || {};
} catch (e) {
  prior = {};
}

let trendSummary = '';
let items = [];

if (parsed && typeof parsed === 'object') {
  trendSummary = cleanText(parsed.trend_summary || parsed.trendSummary || parsed.summary || '');
  const rawItems = Array.isArray(parsed.items)
    ? parsed.items
    : Array.isArray(parsed.articles)
      ? parsed.articles
      : [];

  items = rawItems
    .map((it) => ({
      headline: cleanText(it.headline || it.title || ''),
      breakdown: cleanText(it.breakdown || it.summary || it.description || ''),
      url: validUrl(it.url || it.link || ''),
      source: cleanText(it.source || ''),
    }))
    .filter((it) => it.headline && it.breakdown && it.url)
    .slice(0, 4);
}

// Fallback: keep the digest useful even if the model returned prose/Markdown
if (items.length === 0) {
  const fallbackText = cleanText(raw).slice(0, 4000);
  trendSummary = fallbackText
    ? 'Executive briefing generated by Gemini. Full analysis below.'
    : '';
  const fallbackArticles = prior.articles || [];
  items = fallbackArticles.slice(0, 4).map((a) => ({
    headline: a.title,
    breakdown: a.snippet,
    url: a.url,
    source: a.source,
  }));
}

if (!trendSummary && items.length === 0) {
  throw new Error('LLM returned no usable content. Raw output: ' + String(raw).slice(0, 500));
}

return [
  {
    json: {
      trendSummary:
        trendSummary ||
        'Today\'s briefing covers the most relevant developments across engineering and AI circles.',
      items,
      articleCount: prior.articleCount || 0,
      generatedAt: new Date().toISOString(),
      rawResponse: String(raw || '').slice(0, 2000),
    },
  },
];